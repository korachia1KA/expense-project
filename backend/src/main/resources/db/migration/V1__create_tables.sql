-- =====================================================================================
-- V1: initial schema.
--
-- Flyway runs files named V<version>__<description>.sql in version order, exactly once per
-- database, and records each run in the "flyway_schema_history" table. NEVER edit a migration
-- that has already run somewhere: add a new file (V2__add_xyz.sql) instead.
--
-- The SQL below is deliberately portable: it runs unchanged on PostgreSQL (production) and on
-- H2 in PostgreSQL mode (development and tests).
-- =====================================================================================

-- -------------------------------------------------------------------------------------
-- users: one row per account.
-- -------------------------------------------------------------------------------------
CREATE TABLE users (
    -- Surrogate primary key generated by the database (SQL-standard identity column).
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    -- UNIQUE creates an index and guarantees no two accounts share an email,
    -- even if two registrations race each other.
    email         VARCHAR(255) NOT NULL UNIQUE,
    -- Only the BCrypt HASH is stored, never the plain-text password.
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

-- -------------------------------------------------------------------------------------
-- categories: labels such as "Food" or "Salary". Every user owns their own set.
-- -------------------------------------------------------------------------------------
CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ON DELETE CASCADE: deleting a user deletes their categories too.
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(50)  NOT NULL,
    -- Hex color such as #22c55e, used for chart slices and swatches in the UI.
    color      VARCHAR(7)   NOT NULL,
    -- 'EXPENSE' or 'INCOME' (Java enum stored as text, see @Enumerated(EnumType.STRING)).
    type       VARCHAR(10)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    -- A user cannot have two categories with the same name; different users can.
    CONSTRAINT uq_categories_user_name UNIQUE (user_id, name)
);

-- -------------------------------------------------------------------------------------
-- transactions: every income or expense entry.
-- -------------------------------------------------------------------------------------
CREATE TABLE transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- No ON DELETE clause = RESTRICT: the database refuses to delete a category that still has
    -- transactions. The service layer checks this first to return a friendly 409 message,
    -- and this constraint is the safety net if that check is ever bypassed.
    category_id      BIGINT         NOT NULL REFERENCES categories (id),
    type             VARCHAR(10)    NOT NULL,
    -- NUMERIC(12,2) = exact decimal with up to 10 digits before the point and exactly 2 after.
    -- Never store money as FLOAT/DOUBLE: binary floating point cannot represent 0.10 exactly.
    -- The CHECK constraint repeats the "amount must be positive" rule at the database level.
    amount           NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    description      VARCHAR(255)   NOT NULL,
    -- Named transaction_date because DATE is an SQL keyword.
    transaction_date DATE           NOT NULL,
    notes            VARCHAR(1000),
    created_at       TIMESTAMP      NOT NULL,
    updated_at       TIMESTAMP      NOT NULL
);

-- Almost every query filters by user and a date range (a month), so index exactly that.
CREATE INDEX idx_transactions_user_date ON transactions (user_id, transaction_date);
-- Speeds up "does this category have transactions?" and the per-category aggregates.
CREATE INDEX idx_transactions_category ON transactions (category_id);

-- -------------------------------------------------------------------------------------
-- budgets: a monthly spending limit for one EXPENSE category.
-- -------------------------------------------------------------------------------------
CREATE TABLE budgets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Budgets are meaningless without their category, so they are removed with it.
    category_id  BIGINT         NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    -- Month in ISO format 'YYYY-MM' (e.g. '2026-10'). Text sorts chronologically in this format.
    -- Named budget_month because MONTH is a keyword in some databases.
    budget_month VARCHAR(7)     NOT NULL,
    limit_amount NUMERIC(12, 2) NOT NULL CHECK (limit_amount > 0),
    created_at   TIMESTAMP      NOT NULL,
    updated_at   TIMESTAMP      NOT NULL,
    -- One budget per category per month. PUT /api/budgets relies on this to "upsert".
    CONSTRAINT uq_budgets_user_category_month UNIQUE (user_id, category_id, budget_month)
);
