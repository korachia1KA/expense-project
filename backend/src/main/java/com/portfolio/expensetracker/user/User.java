package com.portfolio.expensetracker.user;

import jakarta.persistence.*;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.time.Instant;
import java.util.Collection;
import java.util.List;

/**
 * An account holder. Every category, transaction and budget belongs to exactly one User.
 *
 * <p><b>Where it fits:</b> the {@code JwtAuthenticationFilter} loads this entity for every
 * authenticated request and stores it in Spring Security's context. Controllers then receive it
 * with {@code @AuthenticationPrincipal User user} and pass it down to services, which use
 * {@code user.getId()} to scope every database query to the caller's own data.
 *
 * <p>{@code @Entity} tells JPA/Hibernate "this class maps to a database table"; each field maps
 * to a column. {@code @Table(name = "users")} names the table explicitly because {@code user} is a
 * reserved word in PostgreSQL.
 *
 * <p>Implementing {@link UserDetails} lets Spring Security use this class directly as the
 * "principal" (the logged-in identity) without a separate adapter class.
 */
@Entity
@Table(name = "users")
public class User implements UserDetails {

    /**
     * {@code @Id} marks the primary key. {@code GenerationType.IDENTITY} means the database
     * generates the value (our SQL uses "GENERATED BY DEFAULT AS IDENTITY"), so it is null until saved.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** {@code @Column} attributes mirror the SQL definition; ddl-auto=validate checks they agree. */
    @Column(nullable = false, length = 100)
    private String name;

    @Column(nullable = false, unique = true, length = 255)
    private String email;

    /** BCrypt hash such as "$2a$10$..."; the plain password is never stored or logged. */
    @Column(name = "password_hash", nullable = false)
    private String passwordHash;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt = Instant.now();

    /** JPA needs a no-argument constructor to create instances when reading rows. {@code protected} hides it from our code. */
    protected User() {
    }

    public User(String name, String email, String passwordHash) {
        this.name = name;
        this.email = email;
        this.passwordHash = passwordHash;
    }

    public Long getId() { return id; }
    public String getName() { return name; }
    public String getEmail() { return email; }
    public Instant getCreatedAt() { return createdAt; }

    // ----- UserDetails contract (used by Spring Security) -----

    /** Roles/permissions. Every account is a plain user; there is no admin area in this app. */
    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return List.of(new SimpleGrantedAuthority("ROLE_USER"));
    }

    /** Spring Security calls this "password", but it is the stored hash. */
    @Override
    public String getPassword() { return passwordHash; }

    /** The email is the login name, and also the "subject" stored inside the JWT. */
    @Override
    public String getUsername() { return email; }
}
